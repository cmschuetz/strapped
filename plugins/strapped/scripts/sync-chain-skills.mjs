#!/usr/bin/env node
// Generate/prune the personal autocomplete wrapper skills for strapped chains:
// one thin skill per resolvable chain at ~/.claude/skills/strapped-run-<chain>/
// SKILL.md whose body only delegates to /strapped:run <chain>. Best-effort
// sugar — /strapped:run stays the canonical entry.
//
// Usage (one JSON object on stdout; misuse = one-line stderr + exit 1):
//   sync-chain-skills.mjs [--home <dir>] [--dry-run]   → { written, unchanged, pruned }
//
// Contract (conventions.md "Wrapper skill sync"):
// - every generated wrapper carries `generated_by: strapped` frontmatter;
//   files WITHOUT that marker are NEVER overwritten or deleted.
// - `chain_source: builtin | anchor` records where the chain resolved from.
// - idempotent: a byte-identical wrapper is a no-op (reported `unchanged`).
// - global prune rule: chain resolution is global (built-ins + anchor,
//   cwd-independent), so a marked wrapper whose chain no longer resolves is
//   pruned; unmarked directories are untouched.
// - --dry-run prints the planned writes/prunes and mutates nothing.
//
// Zero dependencies. Chain resolution is delegated to resolve-chain.mjs
// (--list) so there is exactly one resolver.

import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const RESOLVE_CHAIN_SCRIPT = fileURLToPath(new URL('./resolve-chain.mjs', import.meta.url))
const WRAPPER_PREFIX = 'strapped-run-'
const MARKER_LINE = /^generated_by: strapped$/m

function die(msg) {
  process.stderr.write(`sync-chain-skills.mjs: ${msg}\n`)
  process.exit(1)
}

const out = obj => process.stdout.write(JSON.stringify(obj) + '\n')
const warn = msg => process.stderr.write(`sync-chain-skills.mjs: ${msg}\n`)

// --- args --------------------------------------------------------------------

const args = process.argv.slice(2)
let home = null
let dryRun = false
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--home') {
    home = args[i + 1]
    if (!home) die('--home requires a value')
    i++
  } else if (args[i] === '--dry-run') {
    dryRun = true
  } else {
    die('usage: sync-chain-skills.mjs [--home <dir>] [--dry-run]')
  }
}
home = home || process.env.HOME || homedir()

// --- resolve chains (the one resolver: resolve-chain.mjs --list) --------------

const res = spawnSync(process.execPath, [RESOLVE_CHAIN_SCRIPT, '--list'], {
  encoding: 'utf8',
  env: { ...process.env, HOME: home },
})
if (res.status !== 0) {
  process.stderr.write(res.stderr || 'sync-chain-skills.mjs: chain resolution failed\n')
  process.exit(1)
}
const { chains } = JSON.parse(res.stdout)

// --- write/refresh wrappers ----------------------------------------------------

const skillsDir = join(home, '.claude', 'skills')

function wrapperContent(chain) {
  return `---
name: ${WRAPPER_PREFIX}${chain.name}
description: Run the strapped '${chain.name}' chain (${chain.stages.join(', ')}) to completion — generated by strapped, do not edit
generated_by: strapped
chain_source: ${chain.source}
---

Invoke the Skill (slash command) \`/strapped:run ${chain.name} $ARGUMENTS\` — this wrapper only delegates to the canonical \`/strapped:run\` entry point.
`
}

const written = []
const unchanged = []
const pruned = []

for (const chain of chains) {
  const dir = join(skillsDir, `${WRAPPER_PREFIX}${chain.name}`)
  const file = join(dir, 'SKILL.md')
  const content = wrapperContent(chain)
  if (existsSync(file)) {
    const current = readFileSync(file, 'utf8')
    if (current === content) {
      unchanged.push(chain.name)
      continue
    }
    if (!MARKER_LINE.test(current)) {
      warn(`skipping ${file}: exists without the "generated_by: strapped" marker — not ours, never touched`)
      continue
    }
  }
  written.push(chain.name)
  if (!dryRun) {
    mkdirSync(dir, { recursive: true })
    writeFileSync(file, content)
  }
}

// --- prune stale marked wrappers ------------------------------------------------

const liveDirs = new Set(chains.map(c => `${WRAPPER_PREFIX}${c.name}`))
if (existsSync(skillsDir)) {
  for (const entry of readdirSync(skillsDir)) {
    if (!entry.startsWith(WRAPPER_PREFIX) || liveDirs.has(entry)) continue
    const dir = join(skillsDir, entry)
    if (!statSync(dir).isDirectory()) continue
    const file = join(dir, 'SKILL.md')
    // No SKILL.md, or one without the marker → not ours, never touched.
    if (!existsSync(file) || !MARKER_LINE.test(readFileSync(file, 'utf8'))) continue
    pruned.push(entry.slice(WRAPPER_PREFIX.length))
    if (!dryRun) rmSync(dir, { recursive: true })
  }
}

pruned.sort()
out({ written, unchanged, pruned })
